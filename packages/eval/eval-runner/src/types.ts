/**
 * Types for `@deepseek-ai/dsh-eval-runner` — the eval evidence engine.
 *
 * Defines the run result, per-case verdict, attempt result, delta report,
 * and collaborator interfaces for the batch runner.
 *
 * @module @deepseek-ai/dsh-eval-runner/types
 */

import type { ExecutionArtifact, ExecutionOutcome, ExecutionPort, MultiTurnCaseResult } from '@deepseek-ai/dsh-eval'

// ─── Verdict Mapping ───────────────────────────────────────────────────────────

/**
 * Runner-level verdict for a case. Maps from the eval core's `Verdict` to a
 * broader classification that includes infra failures and unjudged cases:
 * - `correct` — the case passed (all pass_k attempts passed)
 * - `declined` — the agent explicitly declined to answer
 * - `wrong` — the case failed (model gave incorrect answer)
 * - `unjudged` — the case could not be judged (e.g., judge unavailable)
 * - `infra_failure` — infrastructure failure prevented evaluation
 * - `case_defect` — the case itself is unusable and must be fixed, not rerun
 *
 * `infra_failure` and `case_defect` are outside the model's denominator: the
 * first says the environment did not answer, the second says the corpus is
 * broken. Neither is evidence about the model.
 */
export type RunnerVerdict = 'correct' | 'declined' | 'wrong' | 'unjudged' | 'infra_failure' | 'case_defect'

// ─── Attempt Result ────────────────────────────────────────────────────────────

/**
 * LLM SQL semantic judge verdict with per-dimension breakdown.
 */
export interface SqlJudgeVerdict {
  readonly score: number
  readonly rationale: string
  readonly dimensions: Record<string, 0 | 1>
}

/**
 * Result of a single pass_k attempt within a case run.
 */
export interface AttemptResult {
  /** 1-based attempt number within the pass_k sequence. */
  readonly attempt_k: number
  /**
   * The attempt's execution outcome. `not-measured` means execution was never
   * attempted (no executor mounted, or the case declares no EXECUTION
   * expectation) — it is never filled in from a judge score or a default.
   */
  readonly execution_outcome?: ExecutionOutcome
  /** Why the execution outcome came out that way, in the comparator's words. */
  readonly execution_detail?: string
  /** The normalized, re-gradable record of the SQL execution. */
  readonly execution_artifact?: ExecutionArtifact
  /** Whether the delivery assertion passed. */
  readonly delivery_match?: boolean
  /** LLM SQL semantic judge verdict (present when sqlJudge was invoked); reported, never folded into the execution outcome. */
  readonly sql_judge?: SqlJudgeVerdict | undefined
  /** If this attempt hit an infra error, the description. */
  readonly infra_error?: string
  /** If this attempt hit a non-infra error (model/logic failure that threw), the description. */
  readonly error?: string
  /** The SQL generated by the agent (before normalization). */
  readonly generated_sql?: string | null
  /** The expected result value from the eval case. */
  readonly expected_result?: unknown
}

// ─── Case Verdict ──────────────────────────────────────────────────────────────

/**
 * The verdict for one eval case within a batch run.
 */
export interface CaseVerdict {
  /** The case's unique identifier. */
  readonly case_id: string
  /** Per-attempt results for the pass_k run. */
  readonly pass_k_results: AttemptResult[]
  /** The overall verdict for this case. */
  readonly verdict: RunnerVerdict
  /** Latency in milliseconds for the entire case (all pass_k attempts). */
  readonly latency_ms: number
  /** The raw MultiTurnCaseResult from the eval core (for detailed inspection). */
  readonly raw?: MultiTurnCaseResult
}

// ─── Run Config (artifact self-description) ───────────────────────────────────

/**
 * The protocol/semantics/concurrency/model under which a run executed, recorded
 * IN THE RESULT JSON ARTIFACT so a contaminated or mis-attributed run is
 * detectable from its artifact alone (GA-EVAL-REBASELINE item 4).
 *
 * The gap this closes: a 63-case AGA-contaminated eval run went undetected from
 * its JSON because the JSON had no model/concurrency/verdict-semantics — only
 * run_id/timestamp/cases/summary. Recording the full run config in the artifact
 * makes mis-attribution self-evident without a human-maintained audit log.
 *
 * Every field is load-bearing for contamination detection:
 *  - `provider`/`model`: which gateway was actually hit (the AGA-contamination
 *    gap was that the JSON couldn't reveal a wrong gateway was used).
 *  - `verdict_semantics`: pass^k vs best-of-k changes what "correct" means.
 *  - `sql_judge`/`responder`/`scope_id`/`today`: protocol inputs that change outcomes.
 *  - `pass_k`/`concurrency`: runtime semantics that affect flakiness and ordering.
 *  - `query_expansion`/`with_query`/`skip_health_gate`: feature flags that affect results.
 *
 * Optional on `RunResult` (additive — legacy artifacts and callers without a
 * config are not broken); presence is the self-describing guarantee.
 */
export interface RunConfig {
  /** LLM provider route that was actually used for the responder (+ judge). */
  readonly provider: string
  /** LLM model that was actually used for the responder (+ judge). */
  readonly model: string
  /** Number of pass_k attempts per case (runtime semantics). */
  readonly pass_k: number
  /** Concurrency limit for parallel case execution (runtime semantics). */
  readonly concurrency: number
  /** Whether the SQL semantic judge was enabled (!noSqlJudge). */
  readonly sql_judge: boolean
  /** Live verdict semantics (passKVerdict; best-of-k was removed). */
  readonly verdict_semantics: 'pass^k'
  /** Responder mode: NL2SQL engine pipeline or full agent harness. */
  readonly responder: 'engine' | 'harness'
  /** Explicit scopeId for SemanticLayerService + ctx.query adapters. */
  readonly scope_id: string
  /** Reference date YYYYMMDD for time-param extraction (reproducibility). */
  readonly today: string
  /** Whether LLM query expansion before BM25 retrieval was active. */
  readonly query_expansion: boolean
  /** Whether a real query executor (MaxCompute) was mounted. */
  readonly with_query: boolean
  /**
   * Which executor actually ran the SQL — the sidecar path or an equivalent
   * identifier. `with_query` alone cannot tell a real warehouse from the
   * throwaway stand-in sidecar that is the default, so a run recording only
   * the boolean cannot be trusted as a real-execution baseline afterwards.
   * Absent when no executor was mounted.
   */
  readonly executor_identity?: string
  /** Comparator policy version the execution verdicts were graded under. */
  readonly comparator_policy_version: number
  /**
   * How result cells were addressed when comparing. `by-name` and `positional`
   * disagree whenever candidate SQL chose different aliases.
   */
  readonly column_semantics: 'by-name' | 'positional'
  /** Rows an execution artifact stores; digests still cover the full result. */
  readonly max_stored_rows: number
  /**
   * Seconds the warehouse was given to answer synchronously. It bounds both the
   * sidecar's wait window and the derived tool-call timeout, so it decides
   * whether a slow query lands as a result or as `environment-blocked` — which
   * changes the denominator, and therefore may not vary within one batch.
   */
  readonly query_wait_seconds?: number
  /** Whether the health gate pre-flight was skipped. */
  readonly skip_health_gate: boolean
}

// ─── Run Result ────────────────────────────────────────────────────────────────

/**
 * The persisted result of a full batch eval run.
 */
export interface RunResult {
  /** Unique run identifier (UUID or user-supplied). */
  readonly run_id: string
  /** ISO-8601 timestamp when the run started. */
  readonly timestamp: string
  /** Per-case verdicts. */
  readonly cases: CaseVerdict[]
  /** Summary statistics. */
  readonly summary: RunSummary
  /**
   * The protocol/semantics/concurrency/model under which this run executed.
   * Optional (additive — legacy artifacts omit it); when present it makes a
   * contaminated or mis-attributed run detectable from its JSON alone.
   */
  readonly config?: RunConfig
}

/**
 * Summary statistics for a run. `wrong` is the model's denominator; the two
 * excluded categories are counted separately because neither is evidence about
 * the model — `infra_failure` means the environment did not answer,
 * `case_defect` means the corpus is broken.
 */
export interface RunSummary {
  readonly total: number
  readonly correct: number
  readonly wrong: number
  readonly declined: number
  readonly unjudged: number
  readonly infra_failure: number
  readonly case_defect: number
  readonly pass_rate: number
}

// ─── Delta Report ──────────────────────────────────────────────────────────────

/**
 * A flip: one case whose verdict changed between two runs.
 */
export interface CaseFlip {
  readonly case_id: string
  readonly old_verdict: RunnerVerdict
  readonly new_verdict: RunnerVerdict
}

/**
 * Before/after delta report comparing two runs.
 */
export interface DeltaReport {
  /** The run IDs being compared. */
  readonly run_a_id: string
  readonly run_b_id: string
  /** Cases whose verdict flipped. */
  readonly flips: CaseFlip[]
  /** Summary counts. */
  readonly summary: DeltaSummary
}

/**
 * Delta summary: counts of improved, regressed, and unchanged cases.
 */
export interface DeltaSummary {
  readonly improved: number
  readonly regressed: number
  readonly unchanged: number
}

// ─── Collaborator Interfaces ───────────────────────────────────────────────────

/**
 * Abstract agent responder: ask the agent a question, get a conversation
 * transcript back. The runner calls through this interface so the real agent
 * can be wired later (or stubbed for testing).
 */
export interface AgentResponder {
  /** Send a question to the agent and receive a response. */
  respond(question: string, opts?: AgentRespondOpts): Promise<AgentResponse>
}

/** Options for an agent respond call. */
export interface AgentRespondOpts {
  readonly session_id?: string
  readonly scope_id?: string | null
}

/** The agent's response to a question. */
export interface AgentResponse {
  readonly reply: string
  readonly generated_sql: string | null
  readonly transcript?: unknown[]
  readonly schema_context?: string
}

/**
 * Abstract query executor: hands over the capability to run SQL, not a verdict.
 * `execute` returns the provider's raw `QueryOutcome` and evaluation normalizes
 * it — letting each host map the outcome is what forked the adapters that used
 * to do it. Structurally the same as `dsh-eval`'s `ExecutionPort`.
 */
export type QueryExecutor = ExecutionPort

/**
 * Abstract judge provider: judge whether actual output matches expected.
 */
export interface JudgeExecutor {
  /** Judge whether actual matches expected. */
  judge(expected: unknown, actual: string, question: string): Promise<JudgeResult>
}

/** The result of a judge evaluation. */
export interface JudgeResult {
  readonly score: number
  readonly rationale: string
  readonly error?: string
}

// ─── Health Gate ───────────────────────────────────────────────────────────────

/**
 * Result of a single health check.
 */
export interface HealthCheckResult {
  readonly name: string
  readonly healthy: boolean
  readonly message: string
  readonly latency_ms: number
}

/**
 * Result of the pre-flight health gate.
 */
export interface HealthGateResult {
  readonly passed: boolean
  readonly checks: HealthCheckResult[]
  readonly timestamp: string
}

// ─── Batch Runner Options ──────────────────────────────────────────────────────

/**
 * Options for the batch runner.
 */
export interface BatchRunOptions {
  /** Unique run ID. If not provided, a UUID is generated. */
  readonly run_id?: string
  /** Number of pass_k attempts per case (default: 3). */
  readonly pass_k?: number
  /** Maximum infra retries per case (default: 2). */
  readonly max_infra_retries?: number
  /** Output path for the result JSON file. */
  readonly output_path?: string
  /** Whether to skip the health gate. */
  readonly skip_health_gate?: boolean
  /** Wall-clock timeout per attempt in ms (default: null = no timeout). */
  readonly timeout_ms?: number | null
  /** Concurrency limit for parallel case execution (default: 1 = serial). */
  readonly concurrency?: number
  /**
   * Run protocol/semantics/concurrency/model to stamp onto the `RunResult.config`
   * field so the artifact self-describes (GA-EVAL-REBASELINE item 4). The
   * caller (eval-cli) builds this from its known args; when omitted, the
   * result's `config` is undefined (legacy/non-self-describing artifact).
   */
  readonly config?: RunConfig
  /** Progress callback. */
  readonly on_progress?: (completed: number, total: number, case_id: string) => void
}

// ─── Infra Retry ───────────────────────────────────────────────────────────────

/**
 * Classification of a failure for retry purposes.
 */
export type InfraFailureKind = 'connectivity' | 'timeout' | 'rate_limit' | 'transient'

/**
 * Record of an infra retry attempt.
 */
export interface InfraRetryRecord {
  readonly attempt: number
  readonly kind: InfraFailureKind
  readonly error: string
  readonly timestamp: string
}
